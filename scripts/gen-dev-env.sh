#!/usr/bin/env bash
# Generate .env with random local development credentials.
#
# There are no default passwords anywhere in this repo. A shared constant like
# "postgres/postgres" in a compose file is the thing that eventually reaches a
# public network, so dev credentials are random per install and printed once.
set -euo pipefail

cd "$(dirname "$0")/.."

if [[ -f .env ]]; then
  echo "✓ .env already exists — leaving it alone (delete it to regenerate)"
  exit 0
fi

rand() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c "${1:-32}"; }

# Pick host ports that are actually free. Another project's Postgres on 5432 is
# common, and colliding with it is a needless first-run failure.
free_port() {
  local preferred=$1 fallback=$2
  if lsof -nP -iTCP:"$preferred" -sTCP:LISTEN >/dev/null 2>&1; then
    echo "$fallback"
  else
    echo "$preferred"
  fi
}

PG_PORT=$(free_port 5432 55432)
RD_PORT=$(free_port 6379 56379)
S3_PORT_=$(free_port 9000 59000)
S3_CONSOLE=$(free_port 9001 59001)

cat > .env <<EOF
# Generated by scripts/gen-dev-env.sh — local development only. Not committed.
POSTGRES_USER=evalforge
POSTGRES_PASSWORD=$(rand 32)
POSTGRES_DB=evalforge
POSTGRES_PORT=$PG_PORT
POSTGRES_HOST=127.0.0.1

REDIS_PORT=$RD_PORT
REDIS_URL=redis://127.0.0.1:$RD_PORT/0

S3_PORT=$S3_PORT_
S3_CONSOLE_PORT=$S3_CONSOLE
S3_ENDPOINT=http://127.0.0.1:$S3_PORT_
S3_ACCESS_KEY=evalforge
S3_SECRET_KEY=$(rand 40)
S3_BUCKET=evalforge-payloads

# The API refuses to start with ENV=production and a generated dev secret.
ENV=development
JWT_SECRET=$(rand 64)
EOF

chmod 600 .env
echo "✓ wrote .env with random local credentials (mode 600)"
echo "  postgres :$PG_PORT   redis :$RD_PORT   minio :$S3_PORT_ (console :$S3_CONSOLE)"
